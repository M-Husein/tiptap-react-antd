/**
 * Generates src/nodes/CodeBlock/languages.generated.ts from
 * `@codemirror/language-data` — the list of languages CodeMirror supports.
 *
 * Why generate a static copy instead of importing language-data directly:
 * `@codemirror/language-data` statically imports `@codemirror/language`,
 * which statically pulls in `@codemirror/view`/`state` (the editing
 * engine). The schema, the Viewer, and the language <Select> only need
 * names — never parsers — so they read this small static file, and the
 * real language packages are loaded lazily with `import()` only when a
 * code block actually needs highlighting.
 *
 * Staleness is guarded by `npm run test:codeblock`, which regenerates in
 * memory and fails if the committed file differs. Run
 * `npm run generate:code-languages` after upgrading @codemirror/language-data.
 *
 * `--check` writes nothing and exits non-zero if the file is out of date.
 */
import { languages } from "@codemirror/language-data";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const OUT = resolve("src/nodes/CodeBlock/languages.generated.ts");

/** MUST stay in sync with `slugifyLanguageName` in languages.ts. */
const slugify = (name) =>
  name.toLowerCase().replace(/[^a-z0-9+#.]+/g, "-").replace(/^-+|-+$/g, "");

const RESERVED = new Set(["plaintext"]);
const seen = new Map();
const entries = [];

for (const d of languages) {
  const id = slugify(d.name);
  if (RESERVED.has(id)) throw new Error(`language "${d.name}" collides with reserved id "${id}"`);
  if (seen.has(id)) throw new Error(`duplicate language id "${id}": "${d.name}" vs "${seen.get(id)}"`);
  seen.set(id, d.name);
  // LanguageDescription.alias already includes the lowercased name.
  const aliases = [...new Set(d.alias)].filter((a) => a !== id).sort();
  entries.push({ id, label: d.name, aliases });
}
entries.sort((a, b) => a.label.localeCompare(b.label, "en", { sensitivity: "base" }));

const body = entries
  .map((e) => `  { id: ${JSON.stringify(e.id)}, label: ${JSON.stringify(e.label)}, aliases: ${JSON.stringify(e.aliases)} },`)
  .join("\n");

const content = `/* eslint-disable */
// GENERATED by scripts/generate-code-languages.mjs from @codemirror/language-data
// — do not edit by hand. Regenerate with \`npm run generate:code-languages\`.

export interface GeneratedCodeLanguage {
  /** Stable, markdown-fence-safe id: lowercased name, anything but a-z 0-9 + # . becomes "-". */
  id: string;
  /** Display name, exactly as CodeMirror names it. */
  label: string;
  /** Other names/extensions CodeMirror recognizes for it (lowercase). */
  aliases: string[];
}

export const GENERATED_CODE_LANGUAGES: GeneratedCodeLanguage[] = [
${body}
];
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== content) {
    console.error("✗ src/nodes/CodeBlock/languages.generated.ts is out of date — run `npm run generate:code-languages`");
    process.exit(1);
  }
  console.log(`✔ languages.generated.ts is up to date (${entries.length} languages)`);
} else {
  writeFileSync(OUT, content);
  console.log(`wrote ${entries.length} languages -> ${OUT}`);
}
